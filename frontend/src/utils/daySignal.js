// Верхний hero-сигнал «СЕГОДНЯ» на Главной: крупный заголовок-вывод + неброская
// строка, называющая человеческим языком ключевое данное, из которого вывод.
//
// Контент генерит ИИ — потому что ПОРОГИ режимов берутся из ЛИЧНОЙ НОРМЫ владельца
// (долгая память), а не из общих мед. таблиц. Здесь — стабильный «снимок дня» для
// кэша (чтобы hero не перегенерировался каждую минуту), системный промпт с режимами
// и разбор ответа. Есть простой фолбэк без ИИ.

import { WHOOP_DAYS } from './whoop.js'
import { mskNow } from './time.js'

function readWhoop() {
  try { const s = localStorage.getItem('albert-whoop-live'); if (s) return JSON.parse(s) } catch { /* ignore */ }
  return null
}
function readGarmin() {
  try { const s = localStorage.getItem('albert-garmin-live'); if (s) return JSON.parse(s) } catch { /* ignore */ }
  return null
}

function todayIso(now) {
  const p = n => String(n).padStart(2, '0')
  return `${now.getFullYear()}-${p(now.getMonth() + 1)}-${p(now.getDate())}`
}

// Стабильный в пределах дня «снимок» для сигнала: дата + восстановление/сон +
// недельный тренд + стресс + загрузка дня + личная память. БЕЗ минутных величин
// (время, Body Battery), чтобы кэш не сбрасывался каждую минуту.
export function buildSignalData({ events = [], facts = [] } = {}) {
  const now = mskNow()
  const today = todayIso(now)
  const whoop = readWhoop()
  const garmin = readGarmin()

  const lines = [`Дата: ${today}.`]

  if (whoop) {
    lines.push(`Восстановление сегодня ${whoop.recovery}% (утренний балл готовности). Нагрузка ${whoop.strain}/21. Сон ${whoop.sleep?.hoursSlept} ч (${whoop.sleep?.performance}% от нормы сна).`)
    const week = Array.isArray(whoop.week) && whoop.week.length ? whoop.week : WHOOP_DAYS
    if (week?.length) {
      lines.push(`Восстановление по дням недели (для тренда, выше — лучше): ${week.map(d => `${d.day} ${d.recovery}%`).join(', ')}.`)
    }
  } else {
    lines.push('Данных Whoop нет (восстановление/сон неизвестны).')
  }

  const stress = garmin?.stress
  if (stress && (stress.avg ?? stress.current) != null) lines.push(`Стресс (Garmin) ${stress.avg ?? stress.current}/100.`)

  const todayEvents = events.filter(e => e.date === today)
  lines.push(todayEvents.length
    ? `Сегодня событий в расписании: ${todayEvents.length} (${todayEvents.map(e => `${e.start} ${e.title}`).slice(0, 6).join('; ')}).`
    : 'Сегодня расписание свободно (событий нет).')

  lines.push(`Личная память о норме и привычках владельца:\n${facts.length ? facts.map(f => `- ${f.text || f}`).join('\n') : 'пока ничего не запомнено'}`)

  return lines.join('\n')
}

