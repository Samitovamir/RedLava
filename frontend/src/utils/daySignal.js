// Разобрать ответ ИИ в { headline, note }. Терпим к лишним строкам/эху «СЕГОДНЯ».
export function parseSignal(text) {
  const arr = String(text || '').split('\n').map(s => s.trim().replace(/^[«"]|[»"]$/g, '').trim())
    .filter(Boolean).filter(l => !/^сегодня[.:!]?$/i.test(l))
  if (!arr.length) return null
  return { headline: arr[0], note: arr.slice(1).join(' ') }
}

// Простой фолбэк без ИИ: спокойный вывод по восстановлению, всё равно с ключевым данным.
export function fallbackSignal(lang = 'ru') {
  const whoop = readWhoop()
  const r = whoop?.recovery
  if (r == null) {
    return lang === 'en'
      ? { headline: 'A calm day', note: 'Nothing unusual to flag — an ordinary day.' }
      : { headline: 'Спокойный день', note: 'Ничего необычного — день как день.' }
  }
  if (lang === 'en') {
    if (r >= 67) return { headline: 'Some reserve today', note: `Recovery ${r}% — above your usual. Room for a load if you feel like it.` }
    if (r >= 34) return { headline: 'A calm day', note: `Recovery ${r}%. Do as you see fit.` }
    return { headline: 'Body is signalling more than usual', note: `Recovery ${r}% — below your usual. Your call.` }
  }
  if (r >= 67) return { headline: 'Есть запас на сегодня', note: `Восстановление ${r}% — выше обычного. Тело спокойно возьмёт нагрузку, если в настроении.` }
  if (r >= 34) return { headline: 'Спокойный день', note: `Восстановление ${r}%. Делай как считаешь нужным.` }
  return { headline: 'Тело сигналит сильнее обычного', note: `Восстановление ${r}% — ниже твоего обычного. Дальше на твоё усмотрение.` }
}
